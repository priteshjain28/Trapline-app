#!/usr/bin/env python3
"""Generate code from replica/design/tokens.json. Standard library only.

    python3 replica/design/gen_tokens.py          # write tokens.css, tailwind.tokens.cjs, compose/*.kt
    python3 replica/design/gen_tokens.py --check  # also run the WCAG check on light AND dark palettes

tokens.json is the only source of truth. replica-brand edits values there and reruns this.
"""

import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CONTRAST = os.path.join(ROOT, ".claude", "skills", "replica-design", "contrast.py")
HEADER = "Generated by replica/design/gen_tokens.py from tokens.json. Do not edit by hand."


def load():
    with open(os.path.join(HERE, "tokens.json")) as f:
        return json.load(f)


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(p.capitalize() for p in rest)


def pascal(name):
    return "".join(p.capitalize() for p in name.split("-"))


def css(t):
    def block(colors):
        return "\n".join(f"  --color-{k}: {v};" for k, v in colors.items())

    lines = [f"/* {HEADER} */", ":root {", "  color-scheme: light;", block(t["color"])]
    lines.append(f"  --font-sans: {t['font']['sans']};")
    lines.append(f"  --font-mono: {t['font']['mono']};")
    for k, v in t["type"].items():
        lines.append(f"  --text-{k}: {v['size']}px;")
        lines.append(f"  --leading-{k}: {v['line']}px;")
        lines.append(f"  --weight-{k}: {v['weight']};")
    for i, v in enumerate(t["space"]):
        lines.append(f"  --space-{i}: {v}px;")
    for k, v in t["size"].items():
        lines.append(f"  --size-{k}: {v}px;")
    for k, v in t["radius"].items():
        lines.append(f"  --radius-{k}: {v}px;")
    for k, v in t["shadow"].items():
        if not k.startswith("_"):
            lines.append(f"  --shadow-{k}: {v};")
    for k, v in t["motion"].items():
        lines.append(f"  --motion-{k}: {v};")
    lines.append("}")
    dark = block(t["color-dark"])
    lines += [
        "@media (prefers-color-scheme: dark) {",
        "  :root:not([data-theme=\"light\"]) {", "  color-scheme: dark;", dark, "  }", "}",
        "/* an explicit theme wins, on the root or on any element (previews, embedded PDFs) */",
        ":root[data-theme=\"dark\"], [data-theme=\"dark\"] {", "  color-scheme: dark;", dark, "}",
        "[data-theme=\"light\"] {", "  color-scheme: light;", block(t["color"]), "}",
    ]
    return "\n".join(lines) + "\n"


def tailwind(t):
    colors = {k: f"var(--color-{k})" for k in t["color"]}
    font_size = {k: [f"{v['size']}px", {"lineHeight": f"{v['line']}px", "fontWeight": str(v["weight"])}]
                 for k, v in t["type"].items()}
    spacing = {str(i): f"{v}px" for i, v in enumerate(t["space"])}
    theme = {
        "colors": colors,
        "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
        "fontSize": font_size,
        "spacing": spacing,
        "borderRadius": {k: f"{v}px" for k, v in t["radius"].items()},
        "boxShadow": {k: v for k, v in t["shadow"].items() if not k.startswith("_")},
        "transitionDuration": {k: v for k, v in t["motion"].items() if k != "ease"},
        "transitionTimingFunction": {"DEFAULT": t["motion"]["ease"]},
    }
    return (f"// {HEADER}\n// Usage: const tokens = require('./tailwind.tokens.cjs'); module.exports = {{ theme: tokens.theme }}\n"
            f"// Components use roles: bg-surface text-muted border-border, never raw hex.\n"
            f"module.exports = {{ theme: {json.dumps(theme, indent=2)} }};\n")


def kt_color(hexv):
    return "Color(0xFF" + hexv.lstrip("#").upper() + ")"


def compose(t):
    pkg = "app.site.design"
    out = {}
    names = list(t["color"].keys())
    fields = "\n".join(f"    val {camel(n)}: Color," for n in names)
    light = "\n".join(f"    {camel(n)} = {kt_color(v)}," for n, v in t["color"].items())
    dark = "\n".join(f"    {camel(n)} = {kt_color(t['color-dark'][n])}," for n in names)
    out["Colors.kt"] = f"""// {HEADER}
package {pkg}

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/** Colour roles. Screens use these names, never raw colours. */
@Immutable
data class SiteColors(
{fields}
)

val LightSiteColors = SiteColors(
{light}
)

val DarkSiteColors = SiteColors(
{dark}
)
"""
    styles = []
    for k, v in t["type"].items():
        styles.append(f"""    val {k} = TextStyle(
        fontFamily = family,
        fontSize = {v['size']}.sp,
        lineHeight = {v['line']}.sp,
        fontWeight = FontWeight.W{v['weight']},
    )""")
    styles_s = "\n".join(styles)
    out["Type.kt"] = f"""// {HEADER}
package {pkg}

import androidx.compose.runtime.Immutable
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

/**
 * Type scale. `family` is Noto Sans (bundled as res/font, SIL OFL), which also covers
 * Devanagari, Tamil, Telugu, Kannada, Malayalam, Bengali and Odia via its sibling families.
 */
@Immutable
class SiteType(family: FontFamily) {{
{styles_s}
}}
"""
    space = "\n".join(f"    val s{i} = {v}.dp" for i, v in enumerate(t["space"]))
    size = "\n".join(f"    val {camel(k)} = {v}.dp" for k, v in t["size"].items())
    radius = "\n".join(f"    val {k} = RoundedCornerShape({v}.dp)" for k, v in t["radius"].items() if k != "pill")
    out["Dimens.kt"] = f"""// {HEADER}
package {pkg}

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.dp

object Space {{
{space}
}}

object Size {{
{size}
}}

object Radius {{
{radius}
    val pill = RoundedCornerShape(percent = 50)
}}

object Motion {{
    const val FAST_MS = {int(t['motion']['fast'].rstrip('ms'))}
    const val BASE_MS = {int(t['motion']['base'].rstrip('ms'))}
    const val SLOW_MS = {int(t['motion']['slow'].rstrip('ms'))}
}}
"""
    order = [t["series_roles"][k] for k in ("material", "subcontractor", "attendance", "petty_spend", "miscellaneous", "assets")]
    cats = "\n".join(f"    {k.upper()}(\"{k}\")," for k in ("material", "subcontractor", "attendance", "petty_spend", "miscellaneous", "assets"))
    series_when = "\n".join(f"        ExpenseCategory.{k.upper()} -> {camel(s)}"
                            for k, s in zip(("material", "subcontractor", "attendance", "petty_spend", "miscellaneous", "assets"), order))
    out["Theme.kt"] = f"""// {HEADER}
package {pkg}

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.text.font.FontFamily

val LocalSiteColors = staticCompositionLocalOf {{ LightSiteColors }}
val LocalSiteType = staticCompositionLocalOf {{ SiteType(FontFamily.SansSerif) }}

object SiteTheme {{
    val colors: SiteColors @Composable get() = LocalSiteColors.current
    val type: SiteType @Composable get() = LocalSiteType.current
}}

@Composable
fun SiteTheme(
    fontFamily: FontFamily,
    dark: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {{
    CompositionLocalProvider(
        LocalSiteColors provides if (dark) DarkSiteColors else LightSiteColors,
        LocalSiteType provides SiteType(fontFamily),
        content = content,
    )
}}

/** Expense categories in their fixed, validated colour order (S26). Always shown with a text label. */
enum class ExpenseCategory(val key: String) {{
{cats}
}}

fun SiteColors.series(category: ExpenseCategory) =
    when (category) {{
{series_when}
    }}
"""
    return out


def write(path, text):
    with open(path, "w") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def check(t):
    ok = True
    for mode, key in (("light", "color"), ("dark", "color-dark")):
        tmp = dict(t)
        tmp["color"] = t[key]
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
            json.dump(tmp, f)
        print(f"\n== contrast, {mode}")
        r = subprocess.run([sys.executable, "-I", CONTRAST, f.name], capture_output=True, text=True)
        os.unlink(f.name)
        print(r.stdout.strip().splitlines()[-1] if r.returncode == 0 else r.stdout)
        ok = ok and r.returncode == 0
    return ok


def main():
    t = load()
    if set(t["color"]) != set(t["color-dark"]):
        sys.exit("color and color-dark must have the same roles: %s" % (set(t["color"]) ^ set(t["color-dark"])))
    write(os.path.join(HERE, "tokens.css"), css(t))
    write(os.path.join(HERE, "tailwind.tokens.cjs"), tailwind(t))
    os.makedirs(os.path.join(HERE, "compose"), exist_ok=True)
    for name, text in compose(t).items():
        write(os.path.join(HERE, "compose", name), text)
    if "--check" in sys.argv and not check(t):
        sys.exit(1)


if __name__ == "__main__":
    main()
