#!/usr/bin/env python3
"""Convert the Lucide SVGs in replica/design/icons/ to Android vector drawables (res/drawable/ic_*.xml).

    python3 site-app/tools/lucide_to_vector.py

Lucide icons are 24x24, stroke-only (2px, round caps/joins). Handles path, circle, ellipse, rect (with rx),
line, polyline and polygon. Standard library only.
"""

import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "replica", "design", "icons")
OUT = os.path.join(ROOT, "site-app", "app", "src", "main", "res", "drawable")
NS = "{http://www.w3.org/2000/svg}"


def num(v, default=0.0):
    return float(v) if v not in (None, "") else default


def fmt(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def circle(cx, cy, rx, ry):
    return (f"M{fmt(cx - rx)},{fmt(cy)}a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(2 * rx)},0"
            f"a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(-2 * rx)},0Z")


def rect(x, y, w, h, rx, ry):
    if rx == 0 and ry == 0:
        return f"M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
    rx, ry = min(rx, w / 2), min(ry, h / 2)
    return (f"M{fmt(x + rx)},{fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(rx)},{fmt(ry)}"
            f"v{fmt(h - 2 * ry)}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(-rx)},{fmt(ry)}"
            f"h{fmt(-(w - 2 * rx))}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(-rx)},{fmt(-ry)}"
            f"v{fmt(-(h - 2 * ry))}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(rx)},{fmt(-ry)}Z")


def points(p, close):
    nums = [float(n) for n in re.findall(r"-?[\d.]+", p)]
    pts = list(zip(nums[0::2], nums[1::2]))
    d = "M" + " L".join(f"{fmt(a)},{fmt(b)}" for a, b in pts)
    return d + ("Z" if close else "")


def element_path(el):
    tag = el.tag.replace(NS, "")
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        r = num(a.get("r"))
        return circle(num(a.get("cx")), num(a.get("cy")), r, r)
    if tag == "ellipse":
        return circle(num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry")))
    if tag == "rect":
        rx = a.get("rx")
        ry = a.get("ry", rx)
        return rect(num(a.get("x")), num(a.get("y")), num(a.get("width")), num(a.get("height")), num(rx), num(ry))
    if tag == "line":
        return f"M{fmt(num(a.get('x1')))},{fmt(num(a.get('y1')))}L{fmt(num(a.get('x2')))},{fmt(num(a.get('y2')))}"
    if tag == "polyline":
        return points(a["points"], False)
    if tag == "polygon":
        return points(a["points"], True)
    raise ValueError("unsupported element: " + tag)


def convert(svg_text):
    root = ET.fromstring(svg_text)
    paths = []
    for el in root.iter():
        if el is root:
            continue
        tag = el.tag.replace(NS, "")
        if tag in ("title", "desc", "g"):
            continue
        d = element_path(el)
        filled = el.attrib.get("fill") not in (None, "none")
        paths.append(
            f'    <path\n        android:pathData="{d}"\n'
            f'        android:fillColor="{"#FF000000" if filled else "#00000000"}"\n'
            f'        android:strokeColor="#FF000000"\n        android:strokeWidth="2"\n'
            f'        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />'
        )
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Lucide (ISC). Generated by site-app/tools/lucide_to_vector.py; do not edit. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n'
            '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
            + "\n".join(paths) + "\n</vector>\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    n = 0
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".svg"):
            continue
        text = re.sub(r"<!--.*?-->", "", open(os.path.join(SRC, name)).read(), flags=re.S)
        out = os.path.join(OUT, "ic_" + name[:-4].replace("-", "_") + ".xml")
        with open(out, "w") as f:
            f.write(convert(text))
        n += 1
    print(f"wrote {n} vector drawables to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
